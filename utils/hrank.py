"""
hrank.py  –  HRank filter pruning for VGG-16 / CIFAR-10 benchmark

Lin et al. (2020). "HRank: Filter Pruning using High-Rank Feature Map."
CVPR 2020.  arXiv:2002.10179

Method summary
--------------
HRank scores each convolutional filter by the *average rank* of the 2-D
feature maps it produces across a calibration set.

    rank_score[j] = (1/g) * sum_{t=1}^{g}  Rank( o^i_j(t, :, :) )

where  o^i_j(t, :, :)  is the feature map produced by filter j in layer i
for input image t, and  Rank(·)  is the numerical matrix rank (computed via
SVD, identical to torch.linalg.matrix_rank).

Key property (Lin et al., Fig. 2): the average rank of feature maps
generated by a single filter is essentially constant regardless of the
number of images used.  This means a small calibration batch gives a
reliable estimate, making HRank highly efficient.

Filters with *lower* average rank produce less informative feature maps and
are pruned first.  Filters with *higher* rank are the most important.

Integration notes
-----------------
* Follows the same structural weight-surgery contract as apoz.py /
  dropnet.py — hard, physical channel removal via the shared helpers
  imported from utils.apoz.
* Fine-tuning is NOT performed here; it is handled externally by
  training.fine_tune_post_pruning() using the thesis's standardised
  protocol (identical for all 12 methods).
* scope="local"  → layer-wise ranking (prune bottom `ratio` in each layer)
  scope="global" → joint ranking across all layers
"""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

import torch
import torch.nn as nn

# Reuse the structural weight-surgery helpers shared across all methods.
# This guarantees identical channel-removal behaviour and avoids duplication.
