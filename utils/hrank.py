# ─────────────────────────────────────────────────────────────────────────────
# Rank computation
# ─────────────────────────────────────────────────────────────────────────────

def _matrix_rank_batch(feature_maps: torch.Tensor) -> torch.Tensor:
    """
    Compute the numerical rank of a batch of 2-D matrices.

    Parameters
    ----------
    feature_maps : Tensor of shape (B, C, H, W)
        B images, C filters, spatial size H×W.

    Returns
    -------
    ranks : Tensor of shape (C,)
        Sum of per-image ranks for each filter (un-normalised; we normalise
        later across batches to save memory).

    Implementation note
    -------------------
    torch.linalg.matrix_rank uses SVD internally and is equivalent to
    numpy.linalg.matrix_rank.  We iterate over the batch and channel
    dimensions to avoid a single monolithic SVD call that would OOM on GPU
    for large feature maps.  The loop runs on CPU to avoid unnecessary
    device transfers inside the hook.
    """
    feature_maps = feature_maps.cpu().float()
    B, C, H, W = feature_maps.shape
    ranks = torch.zeros(C, dtype=torch.float32)
    for b in range(B):
        for c in range(C):
            fm = feature_maps[b, c]          # (H, W)
            ranks[c] += torch.linalg.matrix_rank(fm).item()
    return ranks                              # shape (C,), sum over B images


def compute_hrank_scores(
    model: nn.Module,
    calib_loader,
    device: torch.device,
    limit_batches: Optional[int] = None,
) -> Dict[str, torch.Tensor]:
    """
    Compute per-filter HRank importance scores for all Conv2d layers.

    For each Conv2d layer i we hook the output of the *following ReLU*
    (post-activation feature maps) and compute their average rank across
    the calibration images:

        score[j] = (1/g) * sum_{t=1}^{g}  Rank( feature_map[t, j, :, :] )

    Hooking post-ReLU is critical in practice: ReLU zeroes out negative
    activations and makes the rank separation between redundant and
    informative filters visible. Pre-ReLU feature maps are typically dense
    and nearly full-rank, which can lead to degenerate/unstable scores.

    Parameters
    ----------
    model         : VGG-16 (torchvision-style, `.features` Sequential).
    calib_loader  : DataLoader; calibration set (no augmentation recommended).
    device        : Compute device.
    limit_batches : Stop after this many batches (quick-test mode).

    Returns
    -------
    scores : dict[layer_name -> 1-D float Tensor of shape (C_out,)]
        Higher score → higher average feature-map rank → more important.
    """
    model.eval()

    # accumulate: sum of per-image ranks across all calibration images
    rank_accum: Dict[str, torch.Tensor] = {}   # layer_name → Tensor (C,)
    image_counts: Dict[str, int] = {}           # layer_name → total images seen

    handles: List = []

    def make_hook(layer_name: str):
        def hook_fn(module: nn.Module, input, output: torch.Tensor):
            # output shape: (B, C, H, W)
            # Rank is only meaningful for 2-D spatial maps; skip 1×1 outputs
            if output.dim() != 4:
                return
            B, C, H, W = output.shape
            if H < 2 or W < 2:
                # 1×1 feature maps give rank <= 1, not informative.
                # Use uniform scores but still include them in averaging.
                batch_ranks = torch.ones(C, dtype=torch.float32)
            else:
                batch_ranks = _matrix_rank_batch(output.detach())  # (C,), cpu
            if layer_name not in rank_accum:
                rank_accum[layer_name] = batch_ranks
                image_counts[layer_name] = B
            else:
                rank_accum[layer_name] += batch_ranks
                image_counts[layer_name] += B
        return hook_fn

    # Register forward hooks on the *ReLU following* each Conv2d (post-activation)
    if hasattr(model, "features") and isinstance(model.features, nn.Sequential):
        children = list(model.features.children())
        for idx, child in enumerate(children):
            if isinstance(child, nn.Conv2d):
                # conv name in torchvision VGG is typically "features.{idx}"
                conv_name = f"features.{idx}"

                # find the next ReLU sibling within a few steps
                target = child  # fallback
                for j in range(idx + 1, min(idx + 4, len(children))):
                    if isinstance(children[j], nn.ReLU):
                        target = children[j]
                        break

                handles.append(target.register_forward_hook(make_hook(conv_name)))
    else:
        # Generic fallback (non-standard architectures): try to hook the
        # next ReLU module after each Conv2d in the module traversal order.
        named = list(model.named_modules())
        for idx, (name, mod) in enumerate(named):
            if isinstance(mod, nn.Conv2d):
                target = mod
                parent_prefix = ".".join(name.split(".")[:-1])
                for j in range(idx + 1, min(idx + 4, len(named))):
                    cname, cmod = named[j]
                    cand_prefix = ".".join(cname.split(".")[:-1])
                    if isinstance(cmod, nn.ReLU) and cand_prefix == parent_prefix:
                        target = cmod
                        break
                handles.append(target.register_forward_hook(make_hook(name)))

    try:
        with torch.no_grad():
            for batch_idx, (images, _) in enumerate(calib_loader):
                if limit_batches is not None and batch_idx >= limit_batches:
                    break
                model(images.to(device))
    finally:
        for h in handles:
            h.remove()

    # Normalise: divide cumulative rank sum by total number of images → average
    return {
        name: rank_accum[name] / image_counts[name]
        for name in rank_accum
        if image_counts.get(name, 0) > 0
    }


# ─────────────────────────────────────────────────────────────────────────────
# Keep-mask construction
# ─────────────────────────────────────────────────────────────────────────────

def _build_keep_masks_local(
    scores: Dict[str, torch.Tensor],
    pruning_ratio: float,
) -> Dict[str, torch.Tensor]:
    """
    Layer-wise ranking (default for HRank).

    Within each layer independently, mark the bottom ``pruning_ratio``
    fraction of filters (lowest average rank → least informative) for
    removal.  Always keeps ≥ 1 filter per layer.

    Returns boolean keep-masks (True = keep this filter).
    """
    masks: Dict[str, torch.Tensor] = {}
    for lname, s in scores.items():
        n_out = len(s)
        n_prune = max(0, min(int(pruning_ratio * n_out), n_out - 1))
        n_keep = n_out - n_prune

        # argsort ascending: lowest rank scores first → prune those
        sorted_idx = torch.argsort(s, descending=False)
        keep_idx = torch.sort(sorted_idx[n_prune:]).values   # top n_keep

        mask = torch.zeros(n_out, dtype=torch.bool)
        mask[keep_idx] = True
        masks[lname] = mask

        n_kept = mask.sum().item()
        n_pruned = (~mask).sum().item()
        avg_rank_kept   = s[mask].mean().item() if mask.any() else 0.0
        avg_rank_pruned = s[~mask].mean().item() if (~mask).any() else 0.0
        print(f"    [{lname}] kept={n_kept}/{n_out} ({100*n_kept/n_out:.1f}%)  "
              f"pruned={n_pruned}/{n_out} ({100*n_pruned/n_out:.1f}%)  "
              f"avg_rank kept={avg_rank_kept:.2f} pruned={avg_rank_pruned:.2f}")
    return masks


# ─────────────────────────────────────────────────────────────────────────────
# Public entry point
# ─────────────────────────────────────────────────────────────────────────────

def apply_hrank_pruning(
    model: nn.Module,
    dataloader,
    target_ratio: float,
    scope: str = "local",
    device: Optional[torch.device] = None,
    limit_batches: Optional[int] = None,
) -> nn.Module:
    """
    Apply HRank-based structural filter pruning to *model*.

    Pipeline
    --------
    1. Forward-pass calibration data  →  average feature-map rank per filter
       (HRank importance score, Lin et al. 2020, Eq. 6).
    2. Build per-layer keep-masks via layer-wise or global ranking:
       lowest-rank filters are pruned first.
    3. Structurally remove pruned channels in forward order, propagating
       dimension changes so consecutive layers remain consistent.
    4. Resize the final classification layer's input dimension only
       (output neurons / num_classes are never changed).

    Unlike the original HRank repo (which stores ranks as .npy files and
    uses a custom VGG variant with baked-in compress_rate), this
    implementation is self-contained and works directly on the
    torchvision-style VGG-16 used throughout this project.

    Parameters
    ----------
    model        : VGG-16 PyTorch model (torchvision-style).
    dataloader   : Calibration DataLoader (test/val split, no augmentation).
    target_ratio : Fraction of filters to *remove* (e.g. 0.3 → remove 30%).
    scope        : ``"local"``  = layer-wise ranking (default, matches paper).
                   ``"global"`` = joint ranking across all layers.
    device       : Compute device; inferred from model parameters if None.
    limit_batches: Cap calibration batches (quick-test mode).

    Returns
    -------
    model : Structurally pruned nn.Module with physically removed channels.
            No fine-tuning applied — handled externally by
            training.fine_tune_post_pruning() under the standardised protocol.

    Notes on computational cost
    ---------------------------
    Rank computation requires per-image SVD on each feature map, so it is
    noticeably slower than APoZ / DropNet for large spatial resolutions.
    For VGG-16 at 224×224 input (as used in this thesis), early conv layers
    produce feature maps up to 224×224 — SVD on those is O(224³) per filter.
    The ``limit_batches`` parameter is therefore important for quick testing.
    """
    if not 0.0 < target_ratio < 1.0:
        raise ValueError(f"target_ratio must be in (0, 1), got {target_ratio}")

    if device is None:
        device = next(model.parameters()).device

    # ── Step 1: HRank scores ──────────────────────────────────────────────────
    print("  Computing HRank scores (average feature-map rank per filter)...")
    scores = compute_hrank_scores(model, dataloader, device, limit_batches)

    if not scores:
        raise RuntimeError(
            "HRank: no feature-map ranks were collected. "
            "Check that the model has Conv2d layers with spatial output (H, W ≥ 2)."
        )

    # ── Step 2: Keep-masks ────────────────────────────────────────────────────
    print(f"  Building pruning masks "
          f"(target: {target_ratio:.0%} removed, scope: {scope})...")

    masks = _build_keep_masks_local(scores, target_ratio)

    # ── Step 3: Structural weight surgery ─────────────────────────────────────
    model = apply_structural_pruning(model, masks)

    print("  HRank pruning complete.")
    return model
